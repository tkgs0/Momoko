def _build_browser_like_headers() -> dict:
    return {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 (KHTML, like Gecko) "
            "Chrome/150.0.0.0 Safari/537.36"
        ),
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8",
        "Accept-Language": "zh-CN,zh;q=0.9,en;q=0.8",
        "Referer": "https://www.bilibili.com/",
        "Origin": "https://www.bilibili.com",
        "Connection": "keep-alive",
        "Upgrade-Insecure-Requests": "1",
        "Sec-Fetch-Site": "same-origin",
        "Sec-Fetch-Mode": "navigate",
        "Sec-Fetch-Dest": "document",
    }


def _expand_short_url(u: str, timeout: float = 8.0) -> str:
    try:
        host: str = urlparse(u).hostname or ""
        if host.lower() not in {"b23.tv", "www.b23.tv"}:
            return u
        
        hdrs: dict[str, str] = {
            "User-Agent": _build_browser_like_headers()["User-Agent"],
            "Referer": "https://www.bilibili.com/",
        }
        
        try:
            with httpx.Client(
                headers=hdrs,
                follow_redirects=True,
                timeout=timeout,
            ) as client:
                resp = client.head(u)
                return str(resp.url) or u
        except Exception:
            try:
                with httpx.Client(
                    headers=hdrs,
                    follow_redirects=True,
                    timeout=timeout,
                ) as client:
                    resp = client.get(u)
                    return str(resp.url) or u
            except Exception:
                return u

    except Exception as e:
        logger.debug(f"bv2mp4: 短链展开失败, 使用原链接 ({u}): {e}")
        return u


def _check_video_file(path: str) -> bool:
    """检查视频文件大小和分辨率"""
    try:
        # 检查文件大小
        path_obj = Path(path)
        if _bv_state["maxsize"] and path_obj.exists():
            size_mb = path_obj.stat().st_size / (1024 * 1024)
            if size_mb > _bv_state["maxsize"]:
                path_obj.unlink()
                return False

        # 检查视频分辨率
        args: Tuple = (
                ffprobe(),
                "-v",
                "error",
                "-select_streams",
                "v:0",
                "-show_entries",
                "stream=width,height",
                "-of",
                "csv=p=0",
                path,
        )
        result = subprocess.run(
            args,
            capture_output=True,
            text=True,
        )
        if result.returncode == 0:
            try:
                _, height = result.stdout.strip().split(",")
                # 检查是否设置了高度限制
                if _bv_state["max_height"] and int(height) > _bv_state["max_height"]:
                    path_obj.unlink()
                    return False
            except ValueError:
                pass
        return True
    except Exception:
        return False


def _build_format_candidates(height_limit: int) -> List[str]:
    """构建格式候选列表"""
    h = height_limit if height_limit and height_limit > 0 else None

    if not h:
        return ["bv*+ba/best"]

    # 根据清晰度限制构建格式候选
    format_map = {
        1080: [
            f"bv*[height>=1080]+ba/best",
            f"bv*[height>=720]+ba/best",
            "bv*+ba/best",
        ],
        720: [f"bv*[height>=720]+ba/best", f"bv*[height>=480]+ba/best", "bv*+ba/best"],
        480: [f"bv*[height>=480]+ba/best", "bv*+ba/best"],
    }

    # 根据高度选择最适合的格式列表
    for threshold, formats in sorted(format_map.items(), reverse=True):
        if h >= threshold:
            return formats

    # 默认格式
    return ["bv*+ba/best"]


def format_selector(ctx):
    """ Select the best video and the best audio that won't result in an mkv.
    NOTE: This is just an example and does not handle all cases """

    # formats are already sorted worst to best
    formats = ctx.get('formats')[::-1]

    # acodec='none' means there is no audio
    best_video = next(f for f in formats
                      if f['vcodec'] != 'none' and ("avc" in f['vcodec'] or "hvc" in f['vcodec']) and f['acodec'] == 'none')

    # find compatible audio extension
    audio_ext = {'mp4': 'm4a', 'webm': 'webm'}[best_video['ext']]
    # vcodec='none' means there is no video
    best_audio = next(f for f in formats if (
        f['acodec'] != 'none' and f['vcodec'] == 'none' and f['ext'] == audio_ext))

    # These are the minimum required fields for a merged format
    yield {
        'format_id': f'{best_video["format_id"]}+{best_audio["format_id"]}',
        'ext': best_video['ext'],
        'requested_formats': [best_video, best_audio],
        # Must be + separated list of protocols
        'protocol': f'{best_video["protocol"]}+{best_audio["protocol"]}'
    }

def _download_with_ytdlp(url: str) -> Tuple[str, str]:

    final_url = _expand_short_url(url)

    # 构建 Cookie 文件
    candidates = _build_format_candidates(_bv_state["max_height"])
    last_err: Optional[Exception] = None

    for _, _ in enumerate(candidates):
        headers = _build_browser_like_headers()
        ydl_opts = {
            "format": format_selector,
            "outtmpl": str(BV_DIR / "%(title).80s [%(id)s].%(ext)s"),
            "noplaylist": True,
            "merge_output_format": "mp4",
            "quiet": False,
            "no_warnings": False,
            "max_filesize" : _bv_state["maxsize"] * 1024 * 1024,  # MB to Bytes
            "http_headers": headers,
            "extractor_args": {
                "bili": {
                    "player_client": ["android", "web"],
                    "lang": ["zh-CN"],
                }
            }
        }

        ydl_opts["ffmpeg_location"] = ffmpeg_dir()
        ydl_opts["cookiefile"] = COOKIES_FILE

        try:
            with YoutubeDL(ydl_opts) as ydl:  #type: ignore
                info = ydl.extract_info(final_url, download=True)
                title = info.get("title") or "B站视频"

                # 获取下载信息
                height = info.get("height", 0)
                logger.info(f"bv2mp4: 下载完成: {title} ({height}p)")

                # 定位文件
                final_path = _locate_final_file(ydl, info)
                if not final_path or not Path(final_path).exists():
                    logger.warning(e := "bv2mp4: 未找到已下载的视频文件，可能未安装 ffmpeg")
                    raise RuntimeError(e)
                return final_path, title
        except DownloadError as e:
            last_err = e
            continue
        except Exception as e:
            last_err = e
            continue

    if last_err:
        logger.warning(e := f"bv2mp4: {last_err}")
        raise RuntimeError(e)

    logger.warning(e := "bv2mp4: 未知错误, 无法下载该视频")
    raise RuntimeError(e)


def _locate_final_file(ydl, info) -> Optional[str]:
    for key in ("requested_downloads", "requested_formats"):
        arr = info.get(key)
        if isinstance(arr, list):
            for it in arr:
                fp = it.get("filepath")
                if fp and os.path.exists(fp):
                    return fp
    for key in ("filepath", "_filename"):
        fp = info.get(key)
        if fp and Path(fp).exists():
            return fp
    # 预测合并后 mp4
    base = ydl.prepare_filename(info)
    root = Path(base).stem
    candidate = root + ".mp4"
    if Path(candidate).exists():
        return candidate
    # 兜底：按视频ID在目录中搜
    vid = info.get("id") or ""
    if vid:
        try:
            files = [BV_DIR / f.name for f in Path(BV_DIR).iterdir() if vid in f.name]
            if files:
                files.sort(key=lambda p: p.stat().st_mtime, reverse=True)
                return str(files[0])
        except Exception:
            pass
    return None


_ytdlp_executor = ThreadPoolExecutor(
    max_workers = int(MAX_WORKERS)
    if is_number(MAX_WORKERS) else 4
)


async def _get_down(url):
    loop = asyncio.get_running_loop()

    return await loop.run_in_executor(
        _ytdlp_executor,
        _download_with_ytdlp,
        url,
    )


