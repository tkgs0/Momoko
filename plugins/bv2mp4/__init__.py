_processing: Set[str] = set()

msg_listen = on_message(priority=15, block=False)

@msg_listen.handle()
async def _(event: GroupMessageEvent):

    group_id = f"{event.group_id}"
    if not group_id in _bv_state["group"]:
        return

    urls = _extract_bili_urls_from_event(event)
    if not urls:
        logger.debug(f"bv2mp4: 消息中未发现B链")
        return

    url = urls[0]
    key = f"{group_id}|{url}"
    if key in _processing:
        logger.debug(f"bv2mp4: 已在处理，忽略重复: {key}")
        return
    _processing.add(key)
    logger.info(f"bv2mp4: 检测到B链")

    try:
        path, title = await _get_down(url)
    except (ImportError, RuntimeError) as e:
        logger.error(f"bv2mp4: 下载环境异常: {e}")
        return
    except Exception as e:
        logger.error(f"bv2mp4: 下载异常: {e}")
        return

    # 检查文件大小和分辨率
    if not _check_video_file(path):
        logger.debug("bv2mp4: 文件超出限制, 停止转发")
        return

    _processing.discard(key)

    try:
        await msg_listen.send(
            message=MessageSegment.video(file=path)
            + Message(f"\n{title or 'B站视频'}"),
        )
    except ActionFailed as e:
        logger.error(f"bv2mp4: {err_info(e)}")
        raise e
    finally:
        try:
            if (path_obj := Path(path)).exists():
                path_obj.unlink()
        except Exception as e:
            logger.warning(f"Failed to delete temp file {path}: {e}")


