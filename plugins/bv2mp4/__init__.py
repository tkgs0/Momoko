def _set_group(args: str, event: MessageEvent) -> str:

    add_list, del_list = [], []

    if oi := args.strip().split():
        gids = list(set([gid for gid in oi if is_number(gid)]))

        add_list = [i for i in gids if not i in _bv_state["group"]]
        del_list = list(set(gids) & set(_bv_state["group"]))

        _bv_state["group"] = [i for i in _bv_state["group"] if i not in del_list]
        _bv_state["group"].extend(add_list)

        _save_state()

        return ''.join([
            f"B链解析:\n",
            f"新增{len(add_list)}个群聊: {add_list}\n" if add_list else '',
            f"取消{len(del_list)}个群聊: {del_list}\n" if del_list else ''
        ])

    if isinstance(event, GroupMessageEvent):
        if (gid := str(event.group_id)) in _bv_state["group"]:
            _bv_state["group"].pop(gid)
            _save_state()
            return "B链解析已禁用"
        else:
            _bv_state["group"].append(gid)
            _save_state()
            return "B链解析已启用"

    return "群号必须为数字!"


def _set_cookies(args, *_) -> str:
    if _ensure_cookiefile(args.strip()):
        return "已配置 bili cookies"
    return "未能正确配置cookies, 请检查cookies格式"


def _set_quality(args, *_) -> str:

    if is_number(size := args.strip()) and int(size) >= 0:

        _bv_state["max_height"] = int(size)
        _save_state()

        return "已取消清晰度限制" if _bv_state["max_height"] == 0 else f"已限制视频清晰度 {_bv_state['max_height']}"

    return '参数必须为大于或等于0的数字!'


def _set_maxsize(args, *_) -> str:

    if is_number(size := args.strip()) and int(size) >= 0:

        _bv_state["maxsize"] = int(size)
        _save_state()

        return "已取消文件限制" if _bv_state["maxsize"] == 0 else f"已限制文件大小 {_bv_state['maxsize']}MB"

    return '参数必须为大于或等于0的数字!'


def _get_list(*_):
    return f"B链解析: 已启用\n{len(_bv_state['group'])}个群聊:\n{_bv_state['group']}" if _bv_state["group"] else "未启用B链解析"


def _clear_list(*_) -> str:
    _bv_state["group"].clear()
    _save_state()
    return "列表已重置"


_ctrl_dict = {
    "s": _set_group,
    "c": _set_cookies,
    "p": _set_quality,
    "x": _set_maxsize,
    "l": _get_list,
    "r": _clear_list,
}


def handle_msg(
    event,
    arg,
) -> str:
    msg = arg.extract_plain_text().strip()

    if not (msg and msg[1:] and msg.startswith("-")):
        return usage

    if (s := msg[1:2]) in list(_ctrl_dict):
        return _ctrl_dict[s](msg[2:], event)

    return usage


